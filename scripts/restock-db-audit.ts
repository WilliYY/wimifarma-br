import assert from "node:assert/strict";
import { Pool } from "pg";
import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "../src/generated/prisma/client";
import { cancelRestock, getAdminRestock, getCustomerRestock, markRestockNotified, prepareRestockDraft, subscribeRestock } from "../src/features/restock/service";

async function main() {
  const connection = new URL(process.env.DATABASE_URL ?? "http://invalid");
  assert.equal(connection.pathname, "/wimifarma_restock_qa_20261019", "Somente o banco sintético dedicado é permitido.");
  assert.ok(["postgres", "127.0.0.1", "localhost"].includes(connection.hostname));
  globalThis.fetch = async () => { throw new Error("External communication disabled in restock QA"); };
  const pool = new Pool({ connectionString: connection.toString(), max: 5 });
  const db = new PrismaClient({ adapter: new PrismaPg(pool) });
  const now = new Date();
  const checks: string[] = [];
  try {
    assert.equal(await db.product.count(), 0, "O banco precisa começar vazio.");
    assert.equal(await db.customer.count(), 0);
    const actor = await db.user.create({ data: { name: "QA sintético", email: "admin@example.invalid", passwordHash: "not-a-password", role: "ADMIN", isActive: true } });
    const customer = await db.customer.create({ data: { name: "Cliente QA sintético", email: "qa@example.invalid", phone: "44999990000" } });
    const other = await db.customer.create({ data: { name: "Outro QA sintético", email: "other@example.invalid", phone: "44999990001" } });
    const session = { user: { id: customer.id, role: "CUSTOMER" } };
    const otherSession = { user: { id: other.id, role: "CUSTOMER" } };
    const product = await db.product.create({ data: { name: "Produto QA sintético", slug: "produto-qa-sintetico", price: 10, stock: 0, status: "ACTIVE" } });
    const input = { productId: product.id, whatsapp: true, email: true, consent: true as const };
    const first = await db.$transaction(tx => subscribeRestock(tx, session, input, now));
    const duplicates = await Promise.all([1, 2].map(() => db.$transaction(tx => subscribeRestock(tx, session, input, now))));
    assert.ok(duplicates.every(result => result.interest.id === first.interest.id));
    assert.equal(await db.restockInterest.count(), 1);
    checks.push("concurrent deduplication");
    await assert.rejects(db.$transaction(tx => cancelRestock(tx, otherSession, first.interest.id)), /não localizado/);
    checks.push("cross-customer cancellation denied");
    await db.product.update({ where: { id: product.id }, data: { stock: 2 } });
    const ready = await db.$transaction(tx => getAdminRestock(tx, 1, "available"));
    assert.equal(ready.counts.available, 1);
    const request = { id: first.interest.id, channel: "EMAIL" as const, updatedAt: ready.data[0].updatedAt };
    const draft = await db.$transaction(tx => prepareRestockDraft(tx, request));
    assert.ok(draft.draft.url.startsWith("mailto:"));
    assert.equal((await db.restockInterest.findUniqueOrThrow({ where: { id: first.interest.id } })).status, "WAITING");
    const partial = await db.$transaction(tx => markRestockNotified(tx, actor.id, request));
    assert.equal(partial.interest.status, "WAITING");
    await assert.rejects(db.$transaction(tx => prepareRestockDraft(tx, request)), /Recarregue/);
    const complete = await db.$transaction(tx => markRestockNotified(tx, actor.id, { ...request, channel: "WHATSAPP", updatedAt: partial.interest.updatedAt }));
    assert.equal(complete.interest.status, "NOTIFIED");
    const completed = await db.restockInterest.findUniqueOrThrow({ where: { id: first.interest.id } });
    assert.equal(completed.phone, null); assert.equal(completed.email, null);
    checks.push("availability, preflight, optimistic version and channel completion");
    await db.product.update({ where: { id: product.id }, data: { stock: 0 } });
    const renewed = await db.$transaction(tx => subscribeRestock(tx, session, input));
    await db.customer.update({ where: { id: customer.id }, data: { phone: "44999990002" } });
    assert.equal((await db.$transaction(tx => getAdminRestock(tx, 1, "all"))).data.length, 0);
    const changed = await db.restockInterest.findUniqueOrThrow({ where: { id: renewed.interest.id } });
    assert.equal(changed.status, "EXPIRED"); assert.equal(changed.phone, null); assert.equal(changed.email, null);
    checks.push("changed contact suppressed before draft");
    const cancelable = await db.$transaction(tx => subscribeRestock(tx, session, input));
    await db.$transaction(tx => cancelRestock(tx, session, cancelable.interest.id));
    const history = await db.$transaction(tx => getCustomerRestock(tx, session));
    assert.ok("interests" in history && history.interests?.some(row => row.status === "CANCELED"));
    await assert.rejects(db.$transaction(tx => prepareRestockDraft(tx, { id: cancelable.interest.id, channel: "EMAIL", updatedAt: cancelable.interest.updatedAt })), /Recarregue/);
    checks.push("cancelled interest history and contact suppression");
    const fillers = Array.from({ length: 51 }, (_, index) => ({ id: `qa-product-${index}`, name: `Produto QA ${index}`, slug: `produto-qa-${index}`, price: 10, stock: 0, status: "ACTIVE" as const }));
    await db.product.createMany({ data: fillers });
    await db.restockInterest.createMany({ data: fillers.slice(0, 49).map(item => ({ customerId: other.id, productId: item.id, whatsapp: false, emailEnabled: true, email: other.email, consentAt: now, expiresAt: new Date(now.getTime() + 86_400_000) })) });
    const quota = await Promise.allSettled(fillers.slice(49).map(item => db.$transaction(tx => subscribeRestock(tx, otherSession, { productId: item.id, whatsapp: false, email: true, consent: true }))));
    assert.equal(quota.filter(result => result.status === "fulfilled").length, 1);
    assert.equal(await db.restockInterest.count({ where: { customerId: other.id, status: "WAITING" } }), 50);
    checks.push("concurrent quota stops at 50");
    assert.equal(await db.order.count(), 0);
    assert.equal(await db.orderItem.count(), 0);
    console.log(JSON.stringify({ ok: true, syntheticOnly: true, externalCommunication: false, ordersCreated: 0, checks }));
  } finally { await db.$disconnect(); await pool.end(); }
}
main().catch(error => { console.error("Restock QA failed", error instanceof Error ? error.message : "unknown"); process.exitCode = 1; });
